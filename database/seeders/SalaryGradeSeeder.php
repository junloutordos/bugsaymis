    public function run(): void
    {
        // ── Seed SSL V T4 2023 (historical, not current) ─────────────────────
        $this->seedTranche(
            rates:         self::RATES_T4_2023,
            tranche:       'SSL V T4 2023',
            effectiveDate: '2023-01-01',
            isCurrent:     false,
        );

        // ── Seed T3 2026 (active tranche) ─────────────────────────────────────
        // First, mark all existing records as not current
        SalaryGrade::query()->update(['is_current' => false]);

        $this->seedTranche(
            rates:         self::RATES_T3_2026,
            tranche:       'SSL VI T3 2026',
            effectiveDate: '2026-01-01',
            isCurrent:     true,
        );
    }

    private function seedTranche(array $rates, string $tranche, string $effectiveDate, bool $isCurrent): void
    {
        $count = 0;

        foreach ($rates as $grade => $steps) {
            foreach ($steps as $stepIndex => $rate) {
                $step = $stepIndex + 1;

                SalaryGrade::updateOrCreate(
                    ['grade' => $grade, 'step' => $step, 'tranche' => $tranche],
                    [
                        'monthly_rate'   => $rate,
                        'effective_date' => $effectiveDate,
                        'is_current'     => $isCurrent,
                    ]
                );
                $count++;
            }
        }

        $label = $isCurrent ? '(active)' : '(historical)';
        $this->command->info("  {$tranche} {$label}: {$count} records seeded.");
    }
