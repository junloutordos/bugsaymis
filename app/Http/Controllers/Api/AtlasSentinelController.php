    /**
     * POST /api/ict-agent/checkin
     *
     * Periodic hardware/peripheral snapshot from an enrolled device. Stores
     * the latest snapshot (overwritten each check-in) and runs it through
     * AtlasSentinelHealthEvaluator, which logs routine findings into the
     * equipment's existing PMS history and tracks actionable findings as
     * open alerts.
     */
    public function checkin(Request $request): JsonResponse
    {
        $validated = $request->validate([
            'cpu'           => ['nullable', 'string', 'max:255'],
            'cpu_usage_pct' => ['nullable', 'numeric'],
            'cpu_temp_c'    => ['nullable', 'numeric'],
            'ram_total_mb'  => ['nullable', 'integer'],
            'ram_free_mb'   => ['nullable', 'integer'],
            'uptime_seconds' => ['nullable', 'integer'],
            'disks'         => ['nullable', 'array'],
            'disks.*.drive'    => ['nullable', 'string', 'max:10'],
            'disks.*.total_gb' => ['nullable', 'numeric'],
            'disks.*.free_gb'  => ['nullable', 'numeric'],
            'printers'      => ['nullable', 'array'],
            'printers.*.name'                  => ['nullable', 'string', 'max:255'],
            'printers.*.detected_error_state'  => ['nullable', 'string', 'max:50'],
            'printers.*.pending_jobs'          => ['nullable', 'integer'],
            'printers.*.is_default'            => ['nullable', 'boolean'],
            'pnp_issues'    => ['nullable', 'array'],
            'pnp_issues.*.device_name' => ['nullable', 'string', 'max:255'],
            'pnp_issues.*.error_code'  => ['nullable', 'string', 'max:50'],
            'network'                      => ['nullable', 'array'],
            'network.gateway_latency_ms'   => ['nullable', 'numeric'],
            'network.packet_loss_pct'      => ['nullable', 'numeric'],
            'network.link_speed_mbps'      => ['nullable', 'integer'],
            'network.link_up'              => ['nullable', 'boolean'],
            'network.local_ip'             => ['nullable', 'string', 'max:45'],
            'services'      => ['nullable', 'array'],
            'services.*.name'   => ['nullable', 'string', 'max:255'],
            'services.*.status' => ['nullable', 'string', 'max:50'],
            'os_version'    => ['nullable', 'string', 'max:255'],
            'agent_version' => ['nullable', 'string', 'max:20'],
            'wifi_ssid'     => ['nullable', 'string', 'max:255'],
            'wifi_bssid'    => ['nullable', 'string', 'max:50'],
            'update_result' => ['nullable', 'array'],
            'update_result.version' => ['nullable', 'string', 'max:20'],
            'update_result.result'  => ['nullable', 'string', 'in:success,failed,failed_service_down,vanished'],
            'update_result.details' => ['nullable', 'string', 'max:2000'],
            'remediation_results'   => ['nullable', 'array'],
            'remediation_results.*.action'       => ['nullable', 'string', 'max:50'],
            'remediation_results.*.target'       => ['nullable', 'string', 'max:255'],
            'remediation_results.*.trigger_code' => ['nullable', 'string', 'max:50'],
            'remediation_results.*.result'       => ['nullable', 'string', 'in:success,failed'],
            'remediation_results.*.details'      => ['nullable', 'string'],
        ]);

        $device = $request->user();

        IctEquipmentHealthSnapshot::updateOrCreate(
            ['device_id' => $device->id],
            ['payload' => $validated, 'recorded_at' => now()]
        );

        $historyRow = IctEquipmentHealthHistory::create([
            'device_id'   => $device->id,
            'payload'     => $validated,
            'recorded_at' => now(),
        ]);

        $networkLocation = $this->networkLocationResolver->resolve($validated['wifi_ssid'] ?? null, $request->ip());

        $deviceUpdate = [
            'last_checkin_at'   => now(),
            'stale_notified_at' => null,
            'os_version'        => $validated['os_version'] ?? $device->os_version,
            'agent_version'     => $validated['agent_version'] ?? $device->agent_version,
        ];

        if ($networkLocation !== $device->network_location) {
            $deviceUpdate['network_location'] = $networkLocation;
            $deviceUpdate['network_location_changed_at'] = now();
        }

        if (isset($validated['update_result']['result'])) {
            $deviceUpdate['last_update_attempted_at'] = now();
            $deviceUpdate['last_update_result'] = $validated['update_result']['result'];
            $deviceUpdate['last_update_details'] = $validated['update_result']['details'] ?? null;
        }

        $device->update($deviceUpdate);

        $this->healthEvaluator->evaluate($device, $validated);
        $this->diagnosticsService->diagnoseFastLoop($device, $validated);
        $this->scoringService->scoreAndStore($device, $validated, $historyRow);

        if (! empty($validated['remediation_results'])) {
            $this->remediationDispatcher->recordResults($device, $validated['remediation_results']);
        }

        $response = ['status' => 'ok'];

        $pendingRemediations = $this->remediationDispatcher->pendingActions($device, $validated);
        if ($pendingRemediations) {
            $response['remediations'] = $pendingRemediations;
        }

        // A backup hiccup must never take health monitoring down with it.
        try {
            $backup = $this->backupService->pendingBackup($device);
            if ($backup) {
                $response['backup'] = $backup;
            }
        } catch (\Throwable $e) {
            logger()->error('Atlas Sentinel: backup dispatch failed during checkin', [
                'device_id' => $device->id,
                'error' => $e->getMessage(),
            ]);
        }

        // A biometric bridge lookup hiccup must never take health monitoring down with it.
        try {
            $biometricBridge = BiometricDevice::where('ict_equipment_device_id', $device->id)
                ->where('is_active', true)
                ->first();
            if ($biometricBridge) {
                $response['biometric_bridge'] = [
                    'device_key'    => $biometricBridge->device_key,
                    'label'         => $biometricBridge->label,
                    'receiver_port' => $biometricBridge->receiver_port,
                ];
            }
        } catch (\Throwable $e) {
            logger()->error('Atlas Sentinel: biometric bridge lookup failed during checkin', [
                'device_id' => $device->id,
                'error' => $e->getMessage(),
            ]);
        }

        $latestRelease = AtlasSentinelRelease::latestRelease();
        $reportedVersion = $validated['agent_version'] ?? $device->agent_version ?? null;
        if ($latestRelease
            && $this->fleetStateService->shouldOfferUpdate($latestRelease->version, $reportedVersion)
            && $this->fleetStateService->tryReserveUpdateOfferSlot($latestRelease->version)) {
            $response['update'] = [
                'version'      => $latestRelease->version,
                'download_url' => route('ict-agent.releases.show', ['encodedKey' => $this->encodeS3Key($latestRelease->s3_key)]),
                'sha256'       => $latestRelease->sha256,
            ];
        }

        return response()->json($response);
    }

