    /**
     * Diffs the incoming hardware snapshot against whatever was recorded
     * last time, logging only the fields that actually changed (a swapped
     * stick of RAM, a replaced disk) before overwriting the latest-only row.
     */
    private function recordHardwareInventory(IctEquipmentDevice $device, array $hardware): void
    {
        $previous = IctEquipmentHardwareInventory::where('device_id', $device->id)->first();

        $fields = ['cpu_model', 'cpu_cores', 'ram_modules', 'disks', 'gpu', 'peripherals', 'battery'];
        if ($previous) {
            foreach ($fields as $field) {
                $oldValue = $previous->{$field};
                $newValue = $hardware[$field] ?? null;

                if (json_encode($oldValue) !== json_encode($newValue)) {
                    IctEquipmentHardwareInventoryChange::create([
                        'device_id'   => $device->id,
                        'field'       => $field,
                        'old_value'   => $oldValue !== null ? json_encode($oldValue) : null,
                        'new_value'   => $newValue !== null ? json_encode($newValue) : null,
                        'detected_at' => now(),
                    ]);
                }
            }
        }

        IctEquipmentHardwareInventory::updateOrCreate(
            ['device_id' => $device->id],
            [
                'cpu_model'   => $hardware['cpu_model'] ?? null,
                'cpu_cores'   => $hardware['cpu_cores'] ?? null,
                'ram_modules' => $hardware['ram_modules'] ?? [],
                'disks'       => $hardware['disks'] ?? [],
                'gpu'         => $hardware['gpu'] ?? null,
                'peripherals' => $hardware['peripherals'] ?? [],
                'battery'     => $hardware['battery'] ?? null,
                'recorded_at' => now(),
            ]
        );
    }

    /**
     * GET /api/ict-agent/releases/{encodedKey}
     *
     * Streams the private S3-stored agent release zip to an enrolled device.
     * Same s3.<base64url> key-encoding pattern as the WFH photo proxy —
     * never expose a raw/public S3 URL for these binaries.
     */
    public function releaseDownload(Request $request, string $encodedKey)
    {
        if (! preg_match('/^[a-zA-Z0-9_.=-]+$/', $encodedKey)) {
            abort(400);
        }

        $s3Key = $this->decodeS3Key($encodedKey);
        // Device tokens may only fetch release artifacts — the encoded key is
        // client-supplied, so without the prefix check it could name any
        // object in the bucket (WFH photos, backups, ...).
        if (! $s3Key || ! str_starts_with($s3Key, 'atlas-sentinel-releases/') || ! Storage::disk('s3')->exists($s3Key)) {
            abort(404);
        }

        // Redirect to a presigned S3 URL so the ~140MB transfer bypasses
        // Cloudflare/ALB/nginx/FPM entirely — fleet-wide updates hold app
        // connections open 16-65s per device and trip the ALB p99 latency
        // alarm. Agents follow the redirect with a default HttpClient (the
        // bearer header is dropped cross-host; the presigned URL needs none)
        // and verify sha256 locally. 30 min matches the agent's own
        // download timeout.
        try {
            return redirect()->away(
                Storage::disk('s3')->temporaryUrl($s3Key, now()->addMinutes(30))
            );
        } catch (\Throwable $e) {
            logger()->warning('Presigned release URL failed, falling back to streaming', ['error' => $e->getMessage()]);
        }

        // Release zips are ~100MB — stream from S3 instead of buffering the
        // whole object in PHP memory, or a fleet-wide update exhausts FPM.
        return response()->stream(function () use ($s3Key) {
            $stream = Storage::disk('s3')->readStream($s3Key);
            fpassthru($stream);
            if (is_resource($stream)) {
                fclose($stream);
            }
        }, 200, [
            'Content-Type'        => 'application/octet-stream',
            'Content-Length'      => (string) Storage::disk('s3')->size($s3Key),
            'Content-Disposition' => 'attachment; filename="' . basename($s3Key) . '"',
        ]);
    }

    private function encodeS3Key(string $s3Key): string
    {
        return 's3.' . rtrim(strtr(base64_encode($s3Key), '+/', '-_'), '=');
    }

    private function decodeS3Key(string $encodedKey): ?string
    {
        if (! str_starts_with($encodedKey, 's3.')) {
            return null;
        }
        $padded = strtr(substr($encodedKey, 3), '-_', '+/');
        $pad = strlen($padded) % 4;
        if ($pad) $padded .= str_repeat('=', 4 - $pad);
        $decoded = base64_decode($padded, true);
        return $decoded !== false ? $decoded : null;
    }

    /**
     * GET /api/ict-agent/alerts
     *
     * Open alerts for the authenticated device — polled by the tray app to
     * decide what to surface to the user.
     */
    public function alerts(Request $request): JsonResponse
    {
        $device = $request->user();

        $alerts = IctEquipmentAlert::where('device_id', $device->id)
            ->where('status', 'open')
            ->orderBy('created_at', 'desc')
            ->get(['id', 'code', 'issue', 'severity', 'created_at']);

        return response()->json(['alerts' => $alerts]);
    }

    /**
     * POST /api/ict-agent/alerts/{alert}/escalate
     *
     * One-click "file an IT Job Request" from the tray app. Submitted as
     * the equipment's assigned owner so it goes through the normal
     * Division Chief → OCD approval chain like any other request — if no
     * owner is assigned yet, this fails with a clear message rather than
     * fabricating a submitter.
     */
    public function escalate(Request $request, IctEquipmentAlert $alert): JsonResponse
    {
        $device = $request->user();

        if ($alert->device_id !== $device->id) {
            abort(403);
        }

        if ($alert->status !== 'open') {
            return response()->json(['message' => 'This alert is no longer open.'], 422);
        }

        $equipment = ICTEquipment::find($alert->equipment_id);
        $owner = $equipment?->owner_id ? User::find($equipment->owner_id) : null;

        if (! $owner) {
            return response()->json([
                'message' => 'This equipment has no assigned owner yet. Ask MIS to assign one in the ICT Equipments page before filing a ticket.',
            ], 422);
        }

        try {
            $jobRequest = $this->jobRequests->createJobRequest([
                'category'    => 'Hardware',
                'title'       => 'Auto-detected issue: ' . ($equipment->description ?? 'ICT equipment'),
                'description' => $alert->issue . " (auto-detected by Atlas Sentinel on {$device->hostname})",
                'priority'    => $alert->severity === 'critical' ? 'high' : 'normal',
                'ict_equipment_id' => $equipment->id,
            ], $owner);
        } catch (\RuntimeException $e) {
            return response()->json(['message' => $e->getMessage()], 422);
        }

        $alert->update(['status' => 'escalated', 'it_job_request_id' => $jobRequest->id]);

        return response()->json([
            'itjr_no' => $jobRequest->itjr_no,
            'job_request_id' => $jobRequest->id,
        ]);
    }

    /**
     * GET /api/ict-agent/device-summary
     *
     * Everything the tray dashboard shows beyond live local metrics:
     * equipment identity, health score, resolved-alert history, last backup
     * run, recent auto-remediations, and the ITJR category list for the
     * "Report a problem" form. Read-only and scoped to the authenticated
     * device — same isolation as alerts().
     */
    public function deviceSummary(Request $request): JsonResponse
    {
        $device = $request->user();
        $equipment = ICTEquipment::find($device->equipment_id);
        $owner = $equipment?->owner_id ? User::find($equipment->owner_id) : null;

        $alertHistory = IctEquipmentAlert::where('device_id', $device->id)
            ->where('status', '<>', 'open')
            ->orderByDesc('created_at')
            ->limit(10)
            ->get(['issue', 'severity', 'status', 'created_at']);

        $lastBackup = IctBackupRun::where('device_id', $device->id)
            ->orderByDesc('id')
            ->first(['status', 'finished_at', 'files_uploaded', 'bytes_uploaded']);

        $recentRemediations = IctEquipmentRemediationLog::where('device_id', $device->id)
            ->orderByDesc('executed_at')
            ->limit(5)
            ->get(['action', 'target', 'result', 'executed_at']);

        return response()->json([
            'device' => [
                'hostname'         => $device->hostname,
                'agent_version'    => $device->agent_version,
                'last_checkin_at'  => $device->last_checkin_at,
                'health_score'     => $device->health_score,
                'risk_tier'        => $device->risk_tier,
                'network_location' => $device->network_location,
            ],
            'equipment' => $equipment ? [
                'property_no' => $equipment->property_no,
                'description' => $equipment->description,
                'category'    => $equipment->category,
                'owner_name'  => $owner?->name,
            ] : null,
            'alert_history'       => $alertHistory,
            'last_backup'         => $lastBackup,
            'recent_remediations' => $recentRemediations,
            'report_categories'   => ITJobCategory::orderBy('name')->pluck('name'),
            'remote_help_enabled' => $this->remoteHelpService->enabled(),
            'remote_help_download_url' => config('atlas_sentinel.remote_help.anydesk.download_url'),
        ]);
    }

    /**
     * POST /api/ict-agent/report-problem
     *
     * User-initiated "Report a problem" from the tray dashboard. Mirrors
     * escalate(): filed as the equipment's assigned owner so it rides the
     * normal Division Chief → OCD approval chain, and refuses rather than
     * fabricating a submitter when no owner is assigned.
     */
    public function reportProblem(Request $request): JsonResponse
    {
        $validated = $request->validate([
            'category'    => ['required', 'string', 'max:100', Rule::exists(ITJobCategory::class, 'name')],
            'description' => ['required', 'string', 'min:10', 'max:2000'],
        ]);

        $device = $request->user();
        $equipment = ICTEquipment::find($device->equipment_id);
        $owner = $equipment?->owner_id ? User::find($equipment->owner_id) : null;

        if (! $owner) {
            return response()->json([
                'message' => 'This equipment has no assigned owner yet. Ask MIS to assign one in the ICT Equipments page before filing a ticket.',
            ], 422);
        }

        try {
            $jobRequest = $this->jobRequests->createJobRequest([
                'category'    => $validated['category'],
                'title'       => 'User-reported issue: ' . ($equipment->description ?? 'ICT equipment'),
                'description' => $validated['description'] . " (reported via Atlas Sentinel on {$device->hostname})",
                'priority'    => 'normal',
                'ict_equipment_id' => $equipment->id,
            ], $owner);
        } catch (\RuntimeException $e) {
            return response()->json(['message' => $e->getMessage()], 422);
        }

        return response()->json([
            'itjr_no' => $jobRequest->itjr_no,
            'job_request_id' => $jobRequest->id,
        ]);
    }

    /**
     * POST /api/ict-agent/backup/{run}/manifest
     *
     * Batched scan manifest from the agent. Returns which of these files
     * still need uploading (new, or content hash changed since last backup).
     */
    public function backupManifest(Request $request, IctBackupRun $run): JsonResponse
    {
        $this->assertOwnedActiveRun($request, $run);

        $validated = $request->validate([
            // 'present' not 'required': an empty manifest (device with zero
            // documents) is legitimate and still needs to start the run.
            'files'                   => ['present', 'array', 'max:500'],
            'files.*.relative_path'   => ['required', 'string', 'max:2000'],
            'files.*.size_bytes'      => ['required', 'integer', 'min:0'],
            'files.*.sha256'          => ['required', 'string', 'regex:/^[0-9a-fA-F]{64}$/'],
            'files.*.mtime'           => ['nullable', 'string', 'max:40'],
        ]);

        return response()->json([
            'needed' => $this->backupService->recordManifest($run, $validated['files']),
        ]);
    }

    /**
     * POST /api/ict-agent/backup/{run}/upload-session
     *
     * Issues a Google Drive resumable-session URI for one file. The agent
     * PUTs the bytes directly to googleapis.com — they never pass through
     * this server, and Drive credentials never reach the device.
     */
    public function backupUploadSession(Request $request, IctBackupRun $run): JsonResponse
    {
        $this->assertOwnedActiveRun($request, $run);

        $validated = $request->validate([
            'relative_path' => ['required', 'string', 'max:2000'],
            'size_bytes'    => ['required', 'integer', 'min:0', 'max:2147483648'],
            'sha256'        => ['required', 'string', 'regex:/^[0-9a-fA-F]{64}$/'],
            'mime_type'     => ['nullable', 'string', 'max:150'],
        ]);

        $sessionUrl = $this->backupService->createUploadSession($run, [
            'relative_path' => $validated['relative_path'],
            'size_bytes'    => $validated['size_bytes'],
            'mime_type'     => $validated['mime_type'] ?? null,
        ]);

        return response()->json(['session_url' => $sessionUrl]);
    }

    /**
     * POST /api/ict-agent/backup/{run}/file-complete
     *
     * The agent finished one direct-to-Drive upload; record the file's new
     * state so future manifest diffs skip it.
     */
    public function backupFileComplete(Request $request, IctBackupRun $run): JsonResponse
    {
        $this->assertOwnedActiveRun($request, $run);

        $validated = $request->validate([
            'relative_path' => ['required', 'string', 'max:2000'],
            'size_bytes'    => ['required', 'integer', 'min:0'],
            'sha256'        => ['required', 'string', 'regex:/^[0-9a-fA-F]{64}$/'],
            'mtime'         => ['nullable', 'string', 'max:40'],
            'drive_file_id' => ['required', 'string', 'max:200'],
        ]);

        $this->backupService->recordFileUploaded($run, $validated);

        return response()->json(['status' => 'ok']);
    }

    /**
     * POST /api/ict-agent/backup/{run}/complete
     *
     * Final stats for the run — closes it out with whatever outcome the
     * agent reports.
     */
    public function backupComplete(Request $request, IctBackupRun $run): JsonResponse
    {
        $this->assertOwnedActiveRun($request, $run);

        $validated = $request->validate([
            'status'        => ['required', 'string', 'in:completed,completed_with_errors,failed'],
            'files_scanned' => ['nullable', 'integer', 'min:0'],
            'files_skipped' => ['nullable', 'integer', 'min:0'],
            'errors'        => ['nullable', 'array', 'max:100'],
            'errors.*'      => ['nullable', 'string', 'max:1000'],
        ]);

        $this->backupService->completeRun($run, $validated);

        return response()->json(['status' => 'ok']);
    }

    /**
     * Backup runs are device-scoped exactly like alerts: a device token can
     * only ever touch its own runs, and only while the run is still active.
     */
    private function assertOwnedActiveRun(Request $request, IctBackupRun $run): void
    {
        if ($run->device_id !== $request->user()->id) {
            abort(403);
        }

        if (! in_array($run->status, ['dispatched', 'running'], true)) {
            abort(422, 'This backup run is no longer active.');
        }
    }
