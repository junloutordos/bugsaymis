    /**
     * POST /api/ict-agent/enroll
     *
     * Exchanges a one-time enrollment token (generated by MIS in the ICT
     * Equipments page) for a long-lived device token. Matches the reported
     * serial number against an existing ict_equipments row; if none exists,
     * creates a draft row for MIS to complete later instead of blocking
     * enrollment.
     */
    public function enroll(Request $request): JsonResponse
    {
        $validated = $request->validate([
            'enrollment_token' => ['required', 'string'],
            'serial_no'        => ['required', 'string', 'max:255'],
            'hostname'         => ['nullable', 'string', 'max:255'],
            'mac_address'      => ['nullable', 'string', 'max:20'],
            'os_version'       => ['nullable', 'string', 'max:255'],
            'agent_version'    => ['nullable', 'string', 'max:20'],
            'model'            => ['nullable', 'string', 'max:255'],
        ]);

        $enrollmentToken = IctEquipmentEnrollmentToken::where('token', $validated['enrollment_token'])
            ->whereNull('revoked_at')
            ->where('expires_at', '>', now())
            ->where(function ($query) {
                $query->whereNull('max_uses')->orWhereColumn('uses_count', '<', 'max_uses');
            })
            ->first();

        if (! $enrollmentToken) {
            return response()->json([
                'message' => 'This enrollment token is invalid, expired, already used up, or revoked.',
            ], 422);
        }

        $serial = trim($validated['serial_no']);
        $hostname = $validated['hostname'] ?? null;
        $mac = $this->normalizeMac($validated['mac_address'] ?? null);
        $matchSource = null;
        $cloneCollision = false;

        $equipment = $this->isUnreliableSerial($serial) ? null : ICTEquipment::where('serial_no', $serial)->first();

        if ($equipment) {
            $matchSource = 'serial';
            $existingDevice = IctEquipmentDevice::where('equipment_id', $equipment->id)->latest('id')->first();

            if ($this->isIdentityConflict($existingDevice, $mac)) {
                $cloneCollision = true;
                logger()->warning('Atlas Sentinel: serial match looked like a cloned/generic desktop; creating Pending Setup equipment instead of reclaiming existing row.', [
                    'matched_equipment_id' => $equipment->id,
                    'matched_device_id' => $existingDevice?->id,
                    'previous_hostname' => $existingDevice?->hostname,
                    'new_hostname' => $hostname,
                    'serial_no' => $serial,
                    'mac_address' => $mac,
                ]);
                $equipment = null;
                $matchSource = null;
            }
        }

        // A MAC-address match is, by construction, always the same MAC — the
        // agent's hostname is expected to change across a reformat/reimage,
        // so it's not treated as a collision signal here.
        if (! $equipment && $mac && ! $cloneCollision) {
            $deviceByMac = IctEquipmentDevice::where('mac_address', $mac)->latest('id')->first();
            if ($deviceByMac) {
                $equipment = ICTEquipment::find($deviceByMac->equipment_id);
                $matchSource = 'mac';
            }
        }

        $linked = (bool) $equipment;

        if (! $equipment) {
            $equipment = $this->createPendingEquipment($validated, $serial, $mac, $cloneCollision);
            $matchSource = $cloneCollision ? 'clone_collision_pending_setup' : 'pending_setup';
        }

        // Re-running install.ps1 on a machine already matched to this
        // equipment (re-enrollment, reinstall) reuses its device row instead
        // of leaving the old one stale forever with a dead token.
        $device = IctEquipmentDevice::where('equipment_id', $equipment->id)->latest('id')->first();

        if ($device && $device->hostname && $hostname && $device->hostname !== $hostname) {
            logger()->warning('Atlas Sentinel: device row reclaimed under a different hostname — possible serial/MAC collision or legitimate reinstall.', [
                'equipment_id' => $equipment->id,
                'previous_hostname' => $device->hostname,
                'new_hostname' => $hostname,
                'serial_no' => $serial,
                'mac_address' => $mac,
            ]);
        }

        $deviceAttributes = [
            'equipment_id'     => $equipment->id,
            'hostname'         => $hostname,
            'mac_address'      => $mac,
            'os_version'       => $validated['os_version'] ?? null,
            'agent_version'    => $validated['agent_version'] ?? null,
            'last_checkin_at'  => now(),
        ];

        if ($device) {
            $device->tokens()->delete();
            $device->update($deviceAttributes);
        } else {
            $device = IctEquipmentDevice::create($deviceAttributes);
        }

        $deviceToken = $device->createToken('ict-agent', ['ict-agent'])->plainTextToken;

        $enrollmentToken->increment('uses_count');
        if (! $enrollmentToken->used_at) {
            $enrollmentToken->update(['used_at' => now()]);
        }

        return response()->json([
            'device_token' => $deviceToken,
            'equipment_id' => $equipment->id,
            'linked'       => $linked,
            'match_source' => $matchSource,
        ], 201);
    }

    private function createPendingEquipment(array $validated, string $serial, ?string $mac, bool $cloneCollision): ICTEquipment
    {
        $hostname = $validated['hostname'] ?? 'unknown host';
        $description = $validated['model'] ?? "Auto-detected device — {$hostname}";

        if ($mac) {
            $description .= " (MAC {$mac})";
        }

        return ICTEquipment::create([
            'category'    => 'Other',
            'serial_no'   => $serial,
            'description' => $description,
            'status'      => 'Pending Setup',
            'remarks'     => $cloneCollision
                ? 'Atlas Sentinel detected a cloned or duplicate hardware identity during enrollment. Review before merging with an existing equipment record.'
                : null,
        ]);
    }

    private function isIdentityConflict(?IctEquipmentDevice $existingDevice, ?string $newMac): bool
    {
        if (! $existingDevice) {
            return false;
        }

        // Hostname is deliberately not part of this check — a reformat/reimage
        // routinely assigns a new hostname to the same physical machine, so
        // treating that alone as a collision forked a duplicate equipment
        // record on every legitimate reformat + re-enroll. MAC address is a
        // hardware property of the NIC and doesn't legitimately change here,
        // so it remains the sole signal for a genuine identity conflict
        // (e.g. a shared/generic serial number reused across two different
        // physical units).
        $existingMac = $this->normalizeMac($existingDevice->mac_address);

        return (bool) ($newMac && $existingMac && $existingMac !== $newMac);
    }

    private function normalizeMac(?string $mac): ?string
    {
        $mac = strtolower(trim((string) $mac));

        return $mac !== '' ? $mac : null;
    }

    private function isUnreliableSerial(?string $serial): bool
    {
        return in_array(strtolower(trim($serial ?? '')), self::UNRELIABLE_SERIALS, true);
    }

